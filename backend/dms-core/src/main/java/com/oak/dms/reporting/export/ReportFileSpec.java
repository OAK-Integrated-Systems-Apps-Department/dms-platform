package com.oak.dms.reporting.export;

import com.oak.dms.reporting.datasource.ReportQuery;
import com.oak.dms.reporting.datasource.ReportRow;
import com.oak.dms.reporting.format.ReportValueFormatter;
import com.oak.dms.reporting.settings.EffectiveReportSettings;

import java.io.IOException;
import java.time.OffsetDateTime;
import java.util.List;
import java.util.Map;

/**
 * Everything an exporter needs to write one report file, apart from the rows themselves.
 *
 * @param title        the template's name, or "Custom report"
 * @param requestedBy  the person the file is for (printed when the organisation shows "generated by")
 * @param filters      the filters in words, relative dates already resolved to the absolute range
 * @param rowCount     rows in the file (after any truncation)
 * @param truncated    the file stops at {@code truncatedAt} rows because the organisation chose "truncate and mark"
 * @param groupColumn  null unless the report is grouped
 * @param groupCounts  rows per group, keyed by the group's display text ("" = no value) - for the group headers
 */
public record ReportFileSpec(String title, OffsetDateTime generatedAt, String requestedBy, List<String> filters,
                             long rowCount, boolean truncated, long truncatedAt, List<ReportQuery.Column> columns,
                             ReportQuery.Column groupColumn, Map<String, Long> groupCounts, ReportValueFormatter formatter,
                             EffectiveReportSettings settings) {

    static final String NO_GROUP_VALUE = "(none)";

    /** Rows arrive one at a time, in the report's order, already resolved (folder path, referenced names). */
    @FunctionalInterface
    public interface RowCursor {
        /** @return the next row, or null when there are no more */
        ReportRow next() throws IOException;
    }

    /** The group a row belongs to, as text. */
    String groupOf(ReportRow row) {
        String text = formatter.display(groupColumn, row.group());
        return text.isEmpty() ? NO_GROUP_VALUE : text;
    }

    /** "Status: Draft (12)" - the header printed above a group. */
    String groupHeader(String group) {
        long n = groupCounts.getOrDefault(NO_GROUP_VALUE.equals(group) ? "" : group, 0L);
        return groupColumn.label() + ": " + group + " (" + n + (n == 1 ? " document)" : " documents)");
    }

    String totalLine() {
        return "Total: " + rowCount + (rowCount == 1 ? " document" : " documents");
    }

    /** One line of the header block; a null label means free text (the title, the organisation's header, a notice). */
    record Info(String label, String value) {
        String line() {
            return label == null ? value : label + ": " + value;
        }
    }

    /**
     * The header block every file carries: title, when and for whom it was generated, what was filtered, how many rows, and the
     * organisation's own header and confidentiality text. Plain text - each exporter sanitises what it writes.
     */
    List<Info> info() {
        List<Info> info = new java.util.ArrayList<>();
        info.add(new Info(null, title));
        if (settings.headerText() != null && !settings.headerText().isBlank()) {
            info.add(new Info(null, settings.headerText()));
        }
        info.add(new Info("Generated at", formatter.timestampWithZone(generatedAt)));
        if (settings.showGeneratedBy() && requestedBy != null) {
            info.add(new Info("Generated for", requestedBy));
        }
        if (settings.showFilterSummary()) {
            if (filters.isEmpty()) {
                info.add(new Info("Filters", "none"));
            } else {
                filters.forEach(f -> info.add(new Info("Filter", f)));
            }
        }
        info.add(new Info("Rows", String.valueOf(rowCount)));
        if (truncated) {
            info.add(new Info(null, "Truncated at " + truncatedAt + " rows"));
        }
        if (settings.confidentialityNotice() != null && !settings.confidentialityNotice().isBlank()) {
            info.add(new Info(null, settings.confidentialityNotice()));
        }
        return info;
    }

    List<String> headerLines() {
        return info().stream().map(Info::line).toList();
    }
}
