#!/usr/bin/env bash
#
# Encrypts every KEY=value line in infra/secrets/dms-core.secrets.env using
# OpenBao's Transit secrets engine (encryption-as-a-service) and writes the
# ciphertext out to infra/secrets/dms-core.secrets.enc.env.
#
# The .enc.env file is safe to commit to git - each value is
# "vault:v1:<base64 aes256-gcm96 ciphertext>" and is useless without access
# to the same OpenBao Transit key (dms-core-secrets). The plaintext
# .secrets.env file must NEVER be committed (see .gitignore).
#
# Requires: bao CLI on PATH, BAO_ADDR and BAO_TOKEN exported, and a Transit
# key already created:
#   bao secrets enable transit               # once per OpenBao instance
#   bao write -f transit/keys/dms-core-secrets
#
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SECRETS_DIR="$REPO_ROOT/infra/secrets"
PLAINTEXT_FILE="${1:-$SECRETS_DIR/dms-core.secrets.env}"
ENCRYPTED_FILE="${2:-$SECRETS_DIR/dms-core.secrets.enc.env}"
TRANSIT_KEY="${OPENBAO_TRANSIT_KEY:-dms-core-secrets}"

command -v bao >/dev/null 2>&1 || { echo "ERROR: 'bao' CLI not found on PATH." >&2; exit 1; }
: "${BAO_ADDR:?Set BAO_ADDR, e.g. export BAO_ADDR=http://127.0.0.1:8200}"
: "${BAO_TOKEN:?Set BAO_TOKEN to a token with encrypt access on transit/$TRANSIT_KEY}"

[ -f "$PLAINTEXT_FILE" ] || { echo "ERROR: $PLAINTEXT_FILE not found." >&2; exit 1; }

echo "==> Encrypting $PLAINTEXT_FILE -> $ENCRYPTED_FILE (transit key: $TRANSIT_KEY)"

{
  echo "# AUTO-GENERATED by scripts/openbao-encrypt-secrets.sh - do not edit by hand."
  echo "# Each value is OpenBao Transit ciphertext (vault:v1:...). Safe to commit."
  echo "# Decrypt with scripts/openbao-decrypt-secrets.sh before docker compose up."
} > "$ENCRYPTED_FILE"

while IFS= read -r line || [ -n "$line" ]; do
  case "$line" in
    ''|'#'*) continue ;;
  esac
  key="${line%%=*}"
  value="${line#*=}"
  b64=$(printf '%s' "$value" | base64 -w0)
  ciphertext=$(bao write -field=ciphertext "transit/encrypt/${TRANSIT_KEY}" plaintext="$b64")
  echo "${key}=${ciphertext}" >> "$ENCRYPTED_FILE"
  echo "    encrypted ${key}"
done < "$PLAINTEXT_FILE"

# Make sure the plaintext source never gets committed by accident.
GITIGNORE="$REPO_ROOT/.gitignore"
if ! grep -qxF "infra/secrets/dms-core.secrets.env" "$GITIGNORE" 2>/dev/null; then
  echo "infra/secrets/dms-core.secrets.env" >> "$GITIGNORE"
  echo "==> Added infra/secrets/dms-core.secrets.env to .gitignore"
fi

echo "==> Done. Commit $ENCRYPTED_FILE, never commit $PLAINTEXT_FILE."
